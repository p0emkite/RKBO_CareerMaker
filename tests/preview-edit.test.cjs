"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path"),vm=require("node:vm");
const root=path.join(__dirname,"..");
const app=fs.readFileSync(path.join(root,"app.js"),"utf8");
const html=fs.readFileSync(path.join(root,"index.html"),"utf8");
assert.match(app,/function seasonCellAt/);
assert.match(app,/function reapplySeasonCorrections/);
assert.match(app,/addEventListener\("click",editSeasonCell\)/);
assert.match(html,/id="cellEditStatus"/);
const card={pit:[["year","시즌",48],["team","소속팀",95],["ERA","방어율",71],["W","승",51]],
 postPit:[["champ","우승",48],["year","시즌",48],["team","소속팀",95],["W","승",51]],bat:[],postBat:[]};
const p={kind:"pitcher",team:"KIA",seasons:{2004:{year:2004,team:"LOT",stats:{W:"7"}},2010:{year:2010,team:"KIA",stats:{W:"3"}}},postSeasons:{}};
const prefix=app.slice(app.indexOf("function seasonCellAt"),app.indexOf("function draw(){",app.indexOf("function seasonCellAt")));
const fn=vm.runInNewContext(prefix+";({seasonCellAt,reapplySeasonCorrections})", {RKBOCard:card,TEAM:{KIA:1,LOT:1,LG:1},console});
const width=1606,columns=card.pit,whole=columns.reduce((a,c)=>a+c[2],0);
const teamX=width*(48+95/2)/whole;
const target=fn.seasonCellAt(p,"regular",teamX,231+28+15);
assert.equal(target.field,"team");assert.equal(target.value,"LOT");assert.equal(target.year,2004);
assert.equal(fn.seasonCellAt(p,"regular",teamX,231+28+2*29+15),null);
p.manualCorrections={"regular:2004":{team:"LG",stats:{W:"12"}}};
fn.reapplySeasonCorrections(p);
assert.equal(p.seasons[2004].team,"LG");assert.equal(p.seasons[2004].stats.W,"12");
assert.equal(p.team,"KIA");assert.equal(p.seasons[2010].team,"KIA");
console.log("Click-to-edit season cell coordinates and manual correction persistence passed.");
