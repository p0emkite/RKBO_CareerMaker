"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const root=path.join(__dirname,"..");
const html=fs.readFileSync(path.join(root,"index.html"),"utf8");
const app=fs.readFileSync(path.join(root,"app.js"),"utf8");
const css=fs.readFileSync(path.join(root,"styles.css"),"utf8");
const block=html.match(/<h2>02 · 선수 선택<\/h2>([\s\S]*?)<div id="playerInfo"/);
assert.ok(block,"Player selector block missing");
const section=block[1];
assert.match(section,/class="season-header-control"/);
assert.match(section,/id="currentSeasonInput"/);
assert.match(section,/id="saveCurrentSeason"/);
assert.match(section,/id="teamSelect"/);
assert.match(section,/id="playerSelect"/);
assert.match(section,/id="includeRetired"/);
assert.doesNotMatch(section,/id="playerSearch"/);
assert.doesNotMatch(app,/playerSearch/);
assert.match(css,/\.player-section-title/);
assert.match(css,/\.player-field-head/);
assert.match(app,/RKBOPlayerFilter\.list\(players,\{team,includeRetired,year\}\)/);
console.log("Compact player selector layout checks passed.");
