"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs"),path=require("node:path");
const root=path.join(__dirname,"..");
const html=fs.readFileSync(path.join(root,"index.html"),"utf8");
const app=fs.readFileSync(path.join(root,"app.js"),"utf8");
const css=fs.readFileSync(path.join(root,"styles.css"),"utf8");
const opening=html.match(/<details\b[^>]*id="recordDatabasePanel"[^>]*>/);
assert.ok(opening,"DB must be a native collapsible details element");
assert.doesNotMatch(opening[0],/\bopen(?:\s|=|>)/,"DB must start CLOSED");
assert.match(html,/<summary class="db-summary"><h2>01 · 기록 데이터베이스/);
assert.match(html,/id="dbStatus"/);
assert.match(html,/id="postHistoryInput"/);
assert.match(html,/id="githubSave"/);
assert.match(css,/\.db-summary:focus-visible/);
assert.match(html,/id="teamGradientStatus"/);
assert.match(html,/cloud-merge\.js/);
assert.match(app,/RKBOCloudMerge\.combine\(remote\.players,players\)/);
assert.match(app,/teamGradients,players/);
assert.match(app,/function saveTeamGradient\(/);
assert.match(app,/function applyTeamGradients\(/);
assert.match(app,/function refreshTeamGradientFields\(/);
assert.match(app,/const config=RKBOGitHubDB\.normalizeTeamGradients/);
const allIds=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
assert.equal(allIds.length,new Set(allIds).size,"Duplicate HTML ids are not allowed");
console.log("Folded records panel and team-gradient persistence UI checks passed.");
